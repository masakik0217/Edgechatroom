const dynamicErrorTranslations = [
  [/^可使用次数必须是 1 到 (\d+) 之间的整数$/, (match) => `使用可能回数は 1 から ${match[1]} までの整数で指定してください`],
  [/^文件大小不能超过 ([\d.]+)MB$/, (match) => `ファイルサイズは ${match[1]} MB 以内にしてください`],
  [/^消息过大，最大 ([\d.]+)KB$/, (match) => `メッセージが大きすぎます（最大 ${match[1]} KB）`],
  [/^Telegram API 请求失败：(\d+)$/, (match) => `Telegram API リクエストに失敗しました: ${match[1]}`],
  [/^Telegram 文件下载失败：(\d+)$/, (match) => `Telegram ファイルのダウンロードに失敗しました: ${match[1]}`],
  [/^演示接口未实现：(\w+) (.+)$/, (match) => `デモ用エンドポイントは未実装です: ${match[1]} ${match[2]}`]
];

export function localizeServerError(message) {
  const fixed = fixedErrorTranslations.get(message);
  if (fixed) return fixed;
  for (const [pattern, translate] of dynamicErrorTranslations) {
    const match = message.match(pattern);
    if (match) return translate(match);
  }
  return message;
}

